# Generate the Table 3 branch coverage medians from data/coverage.csv into /workspace/repro.txt
docker exec zeugma-artifact-container /bin/bash --noprofile --norc -c "python3 - << 'PYEOF'
import pandas as pd

df = pd.read_csv('data/coverage.csv')
df['time'] = pd.to_timedelta(df['time'])

fuzzers = ['BeDiv-Simple', 'BeDiv-Struct', 'RLCheck', 'Zest', 'Zeugma-X', 'Zeugma-1PT', 'Zeugma-2PT', 'Zeugma-Link']
subjects = [
    ('Ant', 'Ant'),
    ('BCEL', 'Bcel'),
    ('Closure', 'Closure'),
    ('Maven', 'Maven'),
    ('Nashorn', 'Nashorn'),
    ('Rhino', 'Rhino'),
    ('Tomcat', 'Tomcat'),
]
times = [
    ('5M', pd.to_timedelta(5, 'm')),
    ('3H', pd.to_timedelta(3, 'h')),
]

header = ['Fuzzer'] + [f'{subj} {t}' for subj, _ in subjects for t, _ in times]
print('| ' + ' | '.join(header) + ' |')
print('| ' + ' | '.join(['---'] * len(header)) + ' |')

for f in fuzzers:
    row = [f]
    for subj_label, subj_data in subjects:
        for t_label, t_val in times:
            series = df[
                (df['fuzzer'] == f)
                & (df['subject'] == subj_data)
                & (df['time'] == t_val)
            ]['covered_branches']
            if series.empty:
                cell = '—'
            else:
                cell = f'{series.median():.1f}'
            row.append(cell)
    print('| ' + ' | '.join(row) + ' |')
PYEOF" > /workspace/repro.txt
# Section 4: Formatting and submission block
echo '<artisan_submit>'
artisan format --expected /workspace/expected.md --repro /workspace/repro.txt
echo '</artisan_submit>'
